"""Flask extension singletons for the Sales-Connections backend.

This module instantiates extension singletons at import time and binds
them to a specific Flask app via ``init_app(app)`` from within the
application factory in :mod:`app.__init__`. The pattern mirrors the
classic Flask-extension idiom (``ext = Extension(); ext.init_app(app)``)
without introducing ``flask-sqlalchemy`` or any other heavyweight Flask
plugin that would coerce the project away from the explicit
transaction-boundary discipline mandated by the AAP.

Singletons exposed by this module:
    * ``db`` - thin SQLAlchemy 2.x wrapper exposing ``engine``,
      ``Session`` (sessionmaker), ``metadata`` (Base.metadata), ``Base``
      (DeclarativeBase subclass), plus ``init_app(app)``, ``session()``,
      and ``dispose()`` lifecycle helpers.
    * ``oauth`` - Authlib ``OAuth`` registration table; per-app provider
      registration is deferred to :func:`init_oauth_clients`.
    * ``logger`` - module-level :class:`structlog.stdlib.BoundLogger`
      bound to the namespace ``"app"``. Picks up the structlog
      configuration applied during :func:`app.create_app` the first
      time it logs.
    * ``metrics_registry`` - dedicated :class:`prometheus_client.CollectorRegistry`
      instance kept separate from the default ``REGISTRY`` so that
      multiple Flask apps (e.g., test fixtures) do not collide on
      duplicate metric registrations.

CRITICAL: The ``db`` singleton is a custom thin wrapper around bare
SQLAlchemy 2.x - NOT ``flask-sqlalchemy``. The wrapper exposes
``init_app(app)`` to consume the Flask config and construct the Engine
plus Session factory at app creation time, but it deliberately omits
flask-sqlalchemy's automatic teardown handler and query-property
abstractions. Service-layer code owns transaction lifecycles
explicitly via ``with db.session() as session: with session.begin():``
blocks (see AAP section 0.5.3 - "Service functions own transactions").

CRITICAL: Importing this module MUST NOT cause network I/O, database
connections, log emission, or any other observable side effect beyond
the construction of the singletons themselves. The module is the
foundation that every other ``app.*`` module depends on; any side
effect here would propagate into every test invocation.
"""

from __future__ import annotations

import contextlib
from typing import TYPE_CHECKING

from authlib.integrations.flask_client import OAuth
